const assert=require('node:assert/strict');
global.window=global;
require('../reference-import/paran-format.js');
require('../reference-import/ris-parser.js');
require('../reference-import/bibtex-parser.js');
require('../paper-data/data-store.js');
const full={authors:'도재학·강범모',title:'제목',authorsEn:'Do Jaehak',titleEn:'A title',journalEn:'Journal',doi:'10.1/test',year:'2012'};
assert.deepEqual(ParanFormat.parse(ParanFormat.stringify(full)),full);
assert.deepEqual(ParanFormat.parse('PARAN  - 1\nTI  - 제목\nEA  - \nER  -'),{title:'제목'});
assert.throws(()=>ParanFormat.parse('PARAN  - 2\nTI  - 제목\nER  -'));
assert.throws(()=>ParanFormat.parse('PARAN  - 1\nTI  - 제목'));
assert.throws(()=>ParanFormat.parse('PARAN  - 1\nTI  - 제목\nER  -\nPARAN  - 1'));
assert.equal(ParanRisParser.parse('TY  - JOUR\nTI  - 예전 논문\nER  -').title,'예전 논문');
assert.equal(ParanBibtexParser.parse('@article{key,title={예전 논문},year={2012}}').title,'예전 논문');
const defs=ParanPaperData.SYSTEM_COLUMNS;
const legacy=defs.filter(c=>!c.optional);
const old=ParanPaperData.normalizeData({columns:legacy,papers:[{title:'기존'}]});
assert.equal(old.columns.length,legacy.length);
assert.equal(old.papers[0].title,'기존');
assert.ok(!Object.hasOwn(old.papers[0],'doi'));
assert.ok(!Object.hasOwn(ParanPaperData.normalizePaper(full,legacy),'doi'));
assert.equal(ParanPaperData.normalizePaper(full,defs).doi,'10.1/test');
assert.ok(!Object.hasOwn(ParanPaperData.normalizePaper({title:'빈값',doi:''},defs),'doi'));
assert.equal(ParanPaperData.normalizePaper(full,[...legacy,{id:'custom-doi',name:'DOI',system:false}]).doi,'10.1/test');
console.log('PASS: PARAN roundtrip, missing optional fields, malformed records, legacy RIS/BibTeX, legacy columns');
